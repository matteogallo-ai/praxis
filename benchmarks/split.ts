#!/usr/bin/env bun
/**
 * The frozen dev/test split of `benchmarks/questions.yaml`.
 *
 * Prompts, models and thresholds are tuned on dev; published live results
 * are measured on test. The split is stratified by format, with the hard
 * case (tag `hard`) as a stratum of its own: within each stratum the ids are
 * sorted, shuffled with a PRNG seeded by `SEED`, and the first
 * `round(n × DEV_FRACTION)` go to dev. A stratum of one therefore lands in
 * test, so every format is measured.
 *
 * `split.yaml` also records the manifest's version and SHA-256, so an edit to
 * `questions.yaml` fails `--check` (run by the test suite) until the split is
 * redrawn and committed with it. Changing `SEED` or `DEV_FRACTION` redraws
 * the split and invalidates anything tuned on the old dev set.
 *
 *   bun run bench:split            # write benchmarks/split.yaml
 *   bun run bench:split --check    # exit 1 if it is stale
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { type BenchmarkEntry, loadManifest } from "./manifest.ts";

export const SEED = 20261103;
export const DEV_FRACTION = 0.4;

const REPO_ROOT = resolve(import.meta.dir, "..");

function paths(root: string): { manifest: string; split: string } {
  return {
    manifest: join(root, "benchmarks", "questions.yaml"),
    split: join(root, "benchmarks", "split.yaml"),
  };
}

export const MANIFEST_PATH = paths(REPO_ROOT).manifest;
export const SPLIT_PATH = paths(REPO_ROOT).split;

export function stratum(entry: BenchmarkEntry): string {
  return entry.tags.includes("hard") ? "hard" : entry.format;
}

/** mulberry32: a small seeded PRNG, so the draw is the same on every machine. */
function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export interface Split {
  dev: string[];
  test: string[];
}

/** Dev and test ids, each in manifest order. */
export function split(entries: readonly BenchmarkEntry[]): Split {
  const random = seededRandom(SEED);
  const devIds = new Set<string>();
  const strata = [...new Set(entries.map(stratum))].sort();
  for (const s of strata) {
    const ids = entries
      .filter((e) => stratum(e) === s)
      .map((e) => e.id)
      .sort();
    for (let i = ids.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      const swap = ids[i] as string;
      ids[i] = ids[j] as string;
      ids[j] = swap;
    }
    for (const id of ids.slice(0, Math.round(ids.length * DEV_FRACTION))) {
      devIds.add(id);
    }
  }
  return {
    dev: entries.filter((e) => devIds.has(e.id)).map((e) => e.id),
    test: entries.filter((e) => !devIds.has(e.id)).map((e) => e.id),
  };
}

export function render(manifestText: string, version: number, s: Split): string {
  const sha = createHash("sha256").update(manifestText).digest("hex");
  const list = (ids: string[]) => ids.map((id) => `  - "${id}"\n`).join("");
  return (
    "# Generated by `bun run bench:split` (benchmarks/split.ts); do not edit.\n" +
    "# Tune on dev; publish live results on test.\n" +
    `seed: ${SEED}\n` +
    `dev_fraction: ${DEV_FRACTION}\n` +
    `manifest_version: ${version}\n` +
    `manifest_sha256: "${sha}"\n` +
    `dev:\n${list(s.dev)}` +
    `test:\n${list(s.test)}`
  );
}

function expected(root: string): { text: string; split: Split } {
  const { manifest: manifestPath } = paths(root);
  const manifestText = readFileSync(manifestPath, "utf-8");
  const manifest = loadManifest(manifestPath);
  const s = split(manifest.benchmarks);
  return { text: render(manifestText, manifest.version, s), split: s };
}

function isCurrent(root: string, text: string): boolean {
  const { split: splitPath } = paths(root);
  return existsSync(splitPath) && readFileSync(splitPath, "utf-8") === text;
}

const STALE =
  "benchmarks/split.yaml does not match questions.yaml; run `bun run bench:split`";

/**
 * The committed split, refused when stale: running "the test set" of an
 * edited manifest would publish results on questions nobody froze.
 */
export function loadSplit(root: string): Split {
  const { text, split: s } = expected(root);
  if (!isCurrent(root, text)) throw new Error(`stale split: ${STALE}`);
  return s;
}

export function main(argv: readonly string[]): number {
  const unknown = argv.filter((a) => a !== "--check");
  if (unknown.length > 0) {
    process.stderr.write(`Unknown argument: ${unknown.join(" ")}\n`);
    return 2;
  }
  const { text, split: s } = expected(REPO_ROOT);
  const counts = `dev ${s.dev.length}, test ${s.test.length} (seed ${SEED})`;
  if (argv.includes("--check")) {
    if (!isCurrent(REPO_ROOT, text)) {
      process.stderr.write(`stale split: ${STALE}\n`);
      return 1;
    }
    process.stdout.write(`split up to date: ${counts}\n`);
    return 0;
  }
  writeFileSync(SPLIT_PATH, text);
  process.stdout.write(`${counts}\n`);
  return 0;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
